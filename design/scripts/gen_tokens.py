#!/usr/bin/env python3
"""Generate code from design/tokens.json (the single source of truth).

    python3 design/scripts/gen_tokens.py          # write design/generated/*
    python3 design/scripts/gen_tokens.py --check  # exit 1 if generated files are stale (CI)

Outputs:
    design/generated/theme.rs   toolkit-agnostic Rust constants (wrap them for iced/egui/Slint)
    design/generated/tokens.css CSS custom properties for the website and docs

Standard library only.
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
TOKENS = ROOT / "tokens.json"
OUT = ROOT / "generated"
HEADER = "GENERATED by design/scripts/gen_tokens.py from design/tokens.json. Do not edit by hand."


def load():
    return json.loads(TOKENS.read_text(encoding="utf-8"))


def entries(group):
    return [(k, v) for k, v in group.items() if not k.startswith("$")]


def rgba(c):
    r, g, b = (round(x * 255) for x in c["components"])
    a = round(c.get("alpha", 1) * 255)
    return r, g, b, a


def px(d):
    return d["value"]


def resolve(ref, t):
    if isinstance(ref, str) and ref.startswith("{"):
        node = t
        for part in ref.strip("{}").split("."):
            node = node[part]
        return node["$value"]
    return ref


def const(name):
    return re.sub(r"[^A-Za-z0-9]", "_", name).upper()


def rust(t):
    L = [f"// {HEADER}", "#![allow(dead_code)]", "",
         "/// An sRGB colour with 8-bit channels.",
         "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
         "pub struct Rgba { pub r: u8, pub g: u8, pub b: u8, pub a: u8 }", "",
         "impl Rgba {",
         "    /// 0xRRGGBB, for toolkits that take a packed colour.",
         "    pub const fn rgb_u32(self) -> u32 { ((self.r as u32) << 16) | ((self.g as u32) << 8) | self.b as u32 }",
         "    /// Channels as 0.0..=1.0 floats (iced, egui Rgba, wgpu).",
         "    pub fn to_f32(self) -> [f32; 4] { [self.r as f32 / 255.0, self.g as f32 / 255.0, self.b as f32 / 255.0, self.a as f32 / 255.0] }",
         "}", "",
         "/// One text style of the type scale.",
         "#[derive(Clone, Copy, Debug, PartialEq)]",
         "pub struct TextStyle { pub family: &'static str, pub size: f32, pub weight: u16, pub line_height: f32, pub letter_spacing_em: f32 }", ""]
    L.append("pub mod color {\n    use super::Rgba;")
    for k, v in entries(t["color"]):
        r, g, b, a = rgba(v["$value"])
        L.append(f"    /// {v.get('$description', '')}")
        L.append(f"    pub const {const(k)}: Rgba = Rgba {{ r: {r}, g: {g}, b: {b}, a: {a} }};")
    L.append("}\n")
    for grp, prefix in (("space", "SPACE_"), ("radius", "")):
        L.append(f"pub mod {grp} {{")
        for k, v in entries(t[grp]):
            L.append(f"    /// {v.get('$description', '')}")
            L.append(f"    pub const {prefix}{const(k)}: f32 = {float(px(v['$value']))};")
        L.append("}\n")
    L.append("pub mod font {")
    for k, v in entries(t["font"]["family"]):
        L.append(f"    /// {v.get('$description', '')} Fallbacks: {', '.join(v['$value'][1:])}.")
        L.append(f"    pub const {const(k)}: &str = \"{v['$value'][0]}\";")
    L.append("}\n")
    L.append("pub mod text {\n    use super::TextStyle;")
    for k, v in entries(t["type"]):
        s = v["$value"]
        fam = resolve(s["fontFamily"], t)[0]
        ls = s["letterSpacing"]["value"] if s["letterSpacing"]["unit"] == "em" else 0.0
        L.append(f"    /// {v.get('$description', '')}")
        L.append(f"    pub const {const(k)}: TextStyle = TextStyle {{ family: \"{fam}\", size: {float(px(s['fontSize']))}, "
                 f"weight: {s['fontWeight']}, line_height: {s['lineHeight']}, letter_spacing_em: {float(ls)} }};")
    L.append("}\n")
    return "\n".join(L)


def css(t):
    def c(v):
        r, g, b, a = rgba(v)
        return f"#{r:02x}{g:02x}{b:02x}" if a == 255 else f"rgba({r}, {g}, {b}, {round(a / 255, 2)})"

    def sh(v):
        v = v if isinstance(v, list) else [v]
        return ", ".join(f"{px(s['offsetX'])}px {px(s['offsetY'])}px {px(s['blur'])}px {px(s['spread'])}px {c(s['color'])}" for s in v)

    L = [f"/* {HEADER} */", ":root {"]
    L += [f"  --{k}: {c(v['$value'])};" for k, v in entries(t["color"])]
    L += [f"  --space-{k}: {px(v['$value'])}px;" for k, v in entries(t["space"])]
    L += [f"  --radius-{k}: {px(v['$value'])}px;" for k, v in entries(t["radius"])]
    L += [f"  --font-{k}: " + ", ".join(f'"{f}"' if " " in f else f for f in v["$value"]) + ";" for k, v in entries(t["font"]["family"])]
    L += [f"  --{k}: {sh(v['$value'])};" for k, v in entries(t["shadow"])]
    L.append("}\n")
    for k, v in entries(t["type"]):
        s = v["$value"]
        fam = s["fontFamily"].strip("{}").split(".")[-1]
        ls = f"{s['letterSpacing']['value']}{s['letterSpacing']['unit']}"
        L.append(f".{k} {{ font: {s['fontWeight']} {px(s['fontSize'])}px/{s['lineHeight']} var(--font-{fam}); letter-spacing: {ls}; }}")
    return "\n".join(L) + "\n"


def main():
    t = load()
    files = {OUT / "theme.rs": rust(t), OUT / "tokens.css": css(t)}
    if "--check" in sys.argv:
        stale = [p for p, body in files.items() if not p.exists() or p.read_text(encoding="utf-8") != body]
        for p in stale:
            print(f"stale: {p.relative_to(ROOT.parent)} — run python3 design/scripts/gen_tokens.py")
        sys.exit(1 if stale else 0)
    OUT.mkdir(exist_ok=True)
    for p, body in files.items():
        p.write_text(body, encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT.parent)}")


if __name__ == "__main__":
    main()
